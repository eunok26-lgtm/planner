/** 그 해의 달 순서와 길이 : [{m, leap, len}, ...] */
function lunarMonths(y) {
  const v = LUNAR_T[y - LUNAR_Y0];
  if (v === undefined) return null;
  const leap = (v >> 13) & 15;
  const bits = v & 0x1FFF;
  const n = leap ? 13 : 12;
  const out = [];
  let i = 0;
  for (let m = 1; m <= 12; m++) {
    out.push({ m, leap: false, len: ((bits >> (n - 1 - i++)) & 1) ? 30 : 29 });
    if (leap === m) out.push({ m, leap: true, len: ((bits >> (n - 1 - i++)) & 1) ? 30 : 29 });
  }
  return out;
}

/** 그 해 음력 1월 1일의 양력 날짜 */
function lunarNewYear(y) {
  const v = LUNAR_T[y - LUNAR_Y0];
  if (v === undefined) return null;
  return addDays(new Date(y, 0, 1), v >> 17);
}

/** 그 해에 윤달이 있으면 몇 월인지 (없으면 0) */
function leapMonthOf(y) {
  const v = LUNAR_T[y - LUNAR_Y0];
  return v === undefined ? 0 : (v >> 13) & 15;
}

/** 음력 → 양력. 없는 날짜면 null */
function lunarToSolar(y, m, d, leap) {
  const months = lunarMonths(y);
  if (!months || d < 1) return null;
  let off = 0;
  for (const x of months) {
    if (x.m === m && x.leap === !!leap) return d > x.len ? null : addDays(lunarNewYear(y), off + d - 1);
    off += x.len;
  }
  return null;
}

/** 양력 → 음력. { y, m, d, leap } (범위 밖이면 null) */
function solarToLunar(date) {
  let y = date.getFullYear();
  let ny = lunarNewYear(y);
  if (!ny) return null;
  if (date < ny) {                       // 아직 음력 설 전이면 지난 해에 속합니다
    y -= 1;
    ny = lunarNewYear(y);
    if (!ny) return null;
  }
  let off = Math.round((date - ny) / 86400000);
  for (const x of lunarMonths(y)) {
    if (off < x.len) return { y, m: x.m, d: off + 1, leap: x.leap };
    off -= x.len;
  }
  return null;
}

/** "음력 7.15" / 윤달이면 "음력 윤7.15" */
function lunarLabel(date) {
  const l = solarToLunar(date);
  return l ? `음력 ${l.leap ? '윤' : ''}${l.m}.${l.d}` : '';
}

/** 그 음력 월·일이 실제로 있는 해인지 */
const lunarExists = (y, m, d, leap) => !!lunarToSolar(y, m, d, leap);
