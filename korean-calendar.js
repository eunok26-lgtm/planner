/* ---------------- 날짜 유틸 ---------------- */
const pad2 = n => String(n).padStart(2, '0');

/** Date → 'YYYY-MM-DD' (로컬 기준, UTC 변환으로 하루 밀리는 문제 없음) */
function ymd(d) {
  return d.getFullYear() + '-' + pad2(d.getMonth() + 1) + '-' + pad2(d.getDate());
}

/** 'YYYY-MM-DD' → Date (로컬 자정) */
function parseYmd(s) {
  const [y, m, d] = s.split('-').map(Number);
  return new Date(y, m - 1, d);
}

function addDays(d, n) {
  const x = new Date(d);
  x.setDate(x.getDate() + n);
  return x;
}

/** 그 주의 시작(월요일) */
function startOfWeek(d, weekStart = 1) {
  const x = new Date(d);
  x.setHours(0, 0, 0, 0);
  x.setDate(x.getDate() - ((x.getDay() - weekStart + 7) % 7));
  return x;
}

function sameDay(a, b) {
  return a.getFullYear() === b.getFullYear()
      && a.getMonth()    === b.getMonth()
      && a.getDate()     === b.getDate();
}

/** 공휴일 이름 (없으면 null) */
function holidayOf(d) {
  const y = KR_HOLIDAYS[d.getFullYear()];
  return y ? (y[pad2(d.getMonth() + 1) + '-' + pad2(d.getDate())] || null) : null;
}

/** 절기·기념일 이름 (없으면 null) */
function termOf(d) {
  const y = KR_TERMS[d.getFullYear()];
  return y ? (y[pad2(d.getMonth() + 1) + '-' + pad2(d.getDate())] || null) : null;
}

/** 날짜 칸에 붙일 성격: 'hol' | 'sun' | 'sat' | '' */
function dayKind(d) {
  if (holidayOf(d)) return 'hol';
  if (d.getDay() === 0) return 'sun';
  if (d.getDay() === 6) return 'sat';
  return '';
}

